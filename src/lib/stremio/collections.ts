export type CollectionTitle = { id: string; type: "movie" | "series"; name: string };

export type Collection = {
  id: string;
  title: string;
  hint: string;
  cover: string;
  items: CollectionTitle[];
};

function movie(id: string, name: string): CollectionTitle {
  return { id, type: "movie", name };
}
function series(id: string, name: string): CollectionTitle {
  return { id, type: "series", name };
}

export function collectionPoster(id: string) {
  return `https://images.metahub.space/poster/medium/${id}/img`;
}

function pack(id: string, title: string, hint: string, items: CollectionTitle[]): Collection {
  return { id, title, hint, cover: collectionPoster(items[0]!.id), items };
}

